-- Manual additive migration for existing instances.
-- Connect as the application schema owner and run this script once before deploying
-- the recovery-enabled users-service. It creates only recovery-token storage and
-- does not update, copy, or delete persisted APP_USERS data.
CREATE TABLE PASSWORD_RESET_TOKENS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER(19,0) NOT NULL,
    TOKEN_HASH VARCHAR2(64) NOT NULL UNIQUE,
    EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT FK_PASSWORD_RESET_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS(ID) ON DELETE CASCADE
);
CREATE INDEX IX_PASSWORD_RESET_USER ON PASSWORD_RESET_TOKENS(USER_ID);
