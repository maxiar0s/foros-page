CREATE TABLE APP_USERS (
    ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    EMAIL VARCHAR2(254) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(10) NOT NULL,
    CONSTRAINT CK_APP_USERS_ROLE CHECK (ROLE IN ('USER', 'ADMIN'))
);

CREATE TABLE FORUM_CATEGORY (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE FORUM_TOPIC (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(200) NOT NULL,
    BODY VARCHAR2(4000) NOT NULL,
    AUTHOR_ID NUMBER(19) NOT NULL,
    CATEGORY_ID NUMBER(19) NOT NULL REFERENCES FORUM_CATEGORY(ID),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE FORUM_COMMENT (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TOPIC_ID NUMBER(19) NOT NULL REFERENCES FORUM_TOPIC(ID),
    AUTHOR_ID NUMBER(19) NOT NULL,
    BODY VARCHAR2(2000) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);

